/**
 * Vendor the web fonts the app head loads from fonts.googleapis.com.
 *
 * The Google Fonts stylesheet was the only render-blocking cross-origin asset
 * in the document head — a signed-out teacher on a slow link waited on a
 * third-party round trip before first paint. Self-hosting latin (+latin-ext)
 * faces in `public/fonts` keeps the identical font fallback behavior with zero
 * external requests on the critical path; the @font-face output is written as
 * `src/styles/fonts.css` (imported by `src/styles.css`).
 *
 * Outfit and JetBrains Mono are OFL; redistribution in the app bundle is
 * permitted (keep this OFL note with the files).
 *
 * Run: node scripts/vendor-fonts.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT_DIR = join(ROOT, "public", "fonts");
const CSS_OUT = join(ROOT, "src", "styles", "fonts.css");

const FONTS_CSS_URL =
  "https://fonts.googleapis.com/css2?family=Outfit:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500;600&display=swap";
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36";

const keepSubsets = ["latin", "latin-ext"];

const css = await (await fetch(FONTS_CSS_URL, { headers: { "user-agent": UA } })).text();
const blocks = css.split("/* ").filter((b) => b.trim());
mkdirSync(OUT_DIR, { recursive: true });
mkdirSync(dirname(CSS_OUT), { recursive: true });

const kept = [];
for (const block of blocks) {
  const comment = block.slice(0, block.indexOf(" */")).trim();
  if (!keepSubsets.some((s) => comment.startsWith(s))) continue;
  const body = block.slice(block.indexOf("@font-face"));
  const family = /font-family: '([^']+)'/.exec(body)?.[1];
  const weight = /font-weight: (\d+)/.exec(body)?.[1];
  const src = /src: url\((\S+?)\) format\('woff2'\)/.exec(body)?.[1];
  const range = /unicode-range: ([^;]+);/.exec(body)?.[1];
  if (!family || !weight || !src || !range) continue;
  const file = `${family.toLowerCase().replaceAll(" ", "-")}-${weight}-${comment.split(" ")[0]}.woff2`;
  const bytes = Buffer.from(await (await fetch(src)).arrayBuffer());
  writeFileSync(join(OUT_DIR, file), bytes);
  kept.push({
    css: `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('/fonts/${file}') format('woff2');\n  unicode-range: ${range};\n}`,
    bytes: bytes.length,
    file,
  });
}

writeFileSync(
  CSS_OUT,
  `/*\n * Self-hosted copies of the faces the app head previously (render-)blocked\n * on at fonts.googleapis.com. Generated by scripts/vendor-fonts.mjs.\n * Outfit and JetBrains Mono are licensed under the SIL Open Font License.\n */\n\n${kept.map((k) => k.css).join("\n\n")}\n`,
);

console.log(`vendored ${kept.length} faces -> public/fonts:`);
for (const k of kept) console.log(`  ${k.file} ${(k.bytes / 1024).toFixed(0)}KB`);
console.log(`wrote ${basename(CSS_OUT)}`);
